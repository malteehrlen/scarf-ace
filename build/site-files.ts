// Vite plugin: writes the files that make the site installable, usable offline and findable:
//  - sw.js        service worker that precaches exactly this build's files (offline + installable app)
//  - robots.txt   and sitemap.xml for search engines (need the absolute site URL)
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import type { Plugin, ResolvedConfig } from 'vite'

/** Not needed offline (or not worth caching on every visitor's device). */
const SKIP = [/\.map$/, /^sw\.js$/, /^social-card\.png$/, /^robots\.txt$/, /^sitemap\.xml$/]

function listFiles(dir: string, base = dir): string[] {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name)
    return e.isDirectory() ? listFiles(full, base) : [path.relative(base, full).split(path.sep).join('/')]
  })
}

// Runs in the browser as /sw.js. VERSION and ASSETS are filled in per build.
const serviceWorker = (version: string, assets: string[]) => `// Generated by build/site-files.ts — do not edit.
const VERSION = ${JSON.stringify(version)}
const ASSETS = ${JSON.stringify(assets)}
const CACHE = 'scarf-ace-' + VERSION
const scoped = (file) => new URL(file, self.registration.scope).href

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map(scoped))))
})

// The new version takes over once every tab of the old one is closed, so a running page never
// loses files it may still load (e.g. the PDF code, fetched on first export).
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('scarf-ace-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    // The page itself: network first so new deploys show up; the cached copy when offline.
    event.respondWith(fetch(request).catch(() => caches.match(scoped('index.html'))))
    return
  }
  // Built files have content hashes in their names, so the cached copy is always right.
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)))
})
`

export function siteFiles(siteUrl: string): Plugin {
  let config: ResolvedConfig
  return {
    name: 'site-files',
    apply: 'build',
    enforce: 'post', // after Vite has added index.html to the bundle
    configResolved(resolved) {
      config = resolved
    },
    generateBundle(_options, bundle) {
      const publicFiles = listFiles(config.publicDir)
      const files = [...new Set([...Object.keys(bundle), ...publicFiles])].filter((f) => !SKIP.some((re) => re.test(f))).sort()

      // The version changes whenever any shipped file changes, so browsers pick up every deploy.
      const hash = crypto.createHash('sha256')
      for (const f of files) {
        hash.update(f)
        const item = bundle[f]
        if (item) hash.update(item.type === 'chunk' ? item.code : item.source)
        else hash.update(fs.readFileSync(path.join(config.publicDir, f)))
      }
      const version = hash.digest('hex').slice(0, 12)

      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, files) })
      if (siteUrl) {
        this.emitFile({ type: 'asset', fileName: 'robots.txt', source: `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}sitemap.xml\n` })
        this.emitFile({
          type: 'asset',
          fileName: 'sitemap.xml',
          source: `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>${siteUrl}</loc></url>\n</urlset>\n`,
        })
      }
    },
  }
}
